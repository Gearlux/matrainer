"""Model packages — a folder holding a model's whole inference graph, its weights and its class names.

The graph used here is the smallest one with every part a real package has: an INCLUDED steps file
(the preprocessing half), a step whose parameter is the weights file (the predictor's slot) and a step
after it (the postprocessing). ``PutField`` stands in for each, so the record a package returns says
exactly which file and which value every step was given.
"""

import pickle
from pathlib import Path
from typing import Any, Dict, Optional

import confluid
import pytest
import yaml
from recordstream import LabelMap
from recordstream.flow.subgraph import Subgraph

from matrainer.artifacts import CLASS_NAMES_FILE
from matrainer.model_package import PACKAGE_FILE, PACKAGE_FORMAT, ModelPackage, PackageModel, read_package
from matrainer.tracking.provenance import file_digest

_HALF = """\
scale:
  op: !class:recordstream.ops.structure.PutField {key: a, value: 1}
"""

_GRAPH = """\
pre:
  include: ../graphs/half.steps.yaml
flow:
  pre:
    op: !class:recordstream.flow.subgraph.Subgraph
      steps: !ref:pre
  predict:
    op: !class:recordstream.ops.structure.PutField {key: weights, value: ""}
    from: pre
  post:
    op: !class:recordstream.ops.structure.PutField {key: b, value: x}
    from: predict
outputs: post
"""

_SLOT = "flow.predict.op.value"


@pytest.fixture
def source(tmp_path: Path) -> Path:
    """A project: ``cfg/model.yaml`` including ``graphs/half.steps.yaml``, and a weights file."""
    root = tmp_path / "project"
    (root / "graphs").mkdir(parents=True)
    (root / "cfg").mkdir()
    (root / "runs").mkdir()
    (root / "graphs" / "half.steps.yaml").write_text(_HALF)
    (root / "cfg" / "model.yaml").write_text(_GRAPH)
    (root / "runs" / "best.pth").write_bytes(b"weights v1")
    return root


def _package(source: Path, out: Path, **kwargs: Any) -> Path:
    settings: Dict[str, Any] = {
        "graph": str(source / "cfg" / "model.yaml"),
        "weights": {_SLOT: str(source / "runs" / "best.pth")},
        "output_dir": str(out),
        **kwargs,
    }
    return Path(PackageModel(**settings).run())


def _values(record: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """A record's entries as plain values (a ``PutField`` writes a ``Label``); ``None`` = the record was dropped."""
    assert record is not None, "a step dropped the record"
    return {key: getattr(value, "value", value) for key, value in record.items()}



def test_the_regenerate_line_is_a_command_that_writes_the_package_again(source: Path, tmp_path: Path) -> None:
    """The header's "To regenerate" line, run as written, rebuilds the package (the generator-provenance rule)."""
    import shlex
    import shutil
    import subprocess
    import sys

    recordstream = Path(sys.executable).parent / "recordstream"
    if not recordstream.is_file():
        pytest.skip(f"no recordstream console script beside {sys.executable}")
    config = tmp_path / "package.yaml"
    config.write_text(
        f"""\
runnable: !class:matrainer.model_package.PackageModel
  graph: {source / "cfg" / "model.yaml"}
  weights: {{{_SLOT}: {source / "runs" / "best.pth"}}}
  output_dir: {tmp_path / "pkg"}
"""
    )
    subprocess.run([str(recordstream), "run", str(config)], cwd=tmp_path, check=True, capture_output=True)
    (line,) = [
        row for row in (tmp_path / "pkg" / PACKAGE_FILE).read_text().splitlines() if row.startswith("# To regenerate: ")
    ]
    command = line.removeprefix("# To regenerate: ").split("   (it replaces")[0]
    assert command.split(" && ", 1)[1].split()[1:] == ["run", shlex.quote(str(config))]
    shutil.rmtree(tmp_path / "pkg" / "weights")

    subprocess.run(["bash", "-c", command], check=True, capture_output=True)

    assert (tmp_path / "pkg" / "weights" / "best.pth").read_bytes() == b"weights v1"

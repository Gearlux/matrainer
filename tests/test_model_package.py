def test_packaging_again_replaces_the_previous_package(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    (out / "stale.txt").write_text("left over")
    (source / "runs" / "best.pth").write_bytes(b"weights v2")

    _package(source, out)

    assert not (out / "stale.txt").exists()
    assert (out / "weights" / "best.pth").read_bytes() == b"weights v2"


def test_a_folder_that_is_not_a_package_is_never_written_into(source: Path, tmp_path: Path) -> None:
    out = tmp_path / "runs"
    out.mkdir()
    (out / "checkpoint.pth").write_bytes(b"precious")

    with pytest.raises(ValueError, match=f"PackageModel: {out} holds files and is not a package"):
        _package(source, out)
    assert sorted(p.name for p in out.iterdir()) == ["checkpoint.pth"]


@pytest.mark.parametrize(
    "settings, message",
    [
        ({"graph": ""}, "'graph' is blank"),
        ({"output_dir": ""}, "'output_dir' is blank"),
        ({"graph": "missing.yaml"}, "the graph missing.yaml does not exist"),
        ({"weights": {_SLOT: "missing.pth"}}, f"the weights of {_SLOT}, missing.pth, do not exist"),
    ],
)
def test_a_missing_input_is_refused_naming_it(
    settings: Dict[str, Any], message: str, source: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(tmp_path)
    with pytest.raises(ValueError, match=message):
        _package(source, tmp_path / "pkg", **settings)
    assert not (tmp_path / "pkg").exists()



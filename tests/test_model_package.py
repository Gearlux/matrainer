def test_a_copied_package_holds_every_graph_file_the_weights_and_the_class_names(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg", class_names=["bird", "cat"])

    assert out == tmp_path / "pkg"
    assert sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file()) == [
        CLASS_NAMES_FILE,
        "graphs/cfg/model.yaml",
        "graphs/graphs/half.steps.yaml",
        PACKAGE_FILE,
        "weights/best.pth",
    ]
    assert (out / "graphs" / "cfg" / "model.yaml").read_text() == _GRAPH
    assert (out / "weights" / "best.pth").read_bytes() == b"weights v1"
    assert LabelMap.load(out / CLASS_NAMES_FILE).class_names == ["bird", "cat"]


def test_the_package_file_names_each_file_with_its_digest(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg", class_names=["bird", "cat"], description="a test model")
    info = read_package(out)

    assert info["format"] == PACKAGE_FORMAT
    assert info["description"] == "a test model"
    assert info["graph"] == "graphs/cfg/model.yaml"
    assert info["graphs"] == "copy" and info["weight_files"] == "copy"
    assert {entry["path"]: entry["sha256"] for entry in info["files"]} == {
        "graphs/cfg/model.yaml": file_digest(out / "graphs" / "cfg" / "model.yaml"),
        "graphs/graphs/half.steps.yaml": file_digest(out / "graphs" / "graphs" / "half.steps.yaml"),
    }
    weight = info["weights"][_SLOT]
    assert weight == {
        "path": "weights/best.pth",
        "size": 10,
        "sha256": file_digest(source / "runs" / "best.pth"),
        "source": str(source / "runs" / "best.pth"),
    }
    assert info["class_names"] == ["bird", "cat"]
    assert "recordstream" in info["packages"]


def test_the_package_file_carries_the_generator_header(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    head = (out / PACKAGE_FILE).read_text().splitlines()[:6]

    assert head[1] == "# AUTO-GENERATED FILE — DO NOT EDIT BY HAND"
    assert head[2].startswith("# Generated by: ")
    assert head[3] == "# Source: matrainer/model_package.py (PackageModel)"
    assert head[4].startswith("# To regenerate: ")


def test_a_package_without_class_names_writes_none(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")

    assert not (out / CLASS_NAMES_FILE).exists()
    assert read_package(out)["class_names"] is None



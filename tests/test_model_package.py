def test_a_package_runs_its_graph_with_the_weights_inside_it(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")

    record = ModelPackage(path=str(out))({})

    assert _values(record) == {"a": 1, "weights": str(out / "weights" / "best.pth"), "b": "x"}


def test_a_package_gives_what_its_source_graph_gives(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    document = confluid.load({"include": [str(source / "cfg" / "model.yaml")], _SLOT: "w"})
    direct = Subgraph(steps=document["flow"], result=document["outputs"])({"x": 0})

    packaged = ModelPackage(path=str(out), overrides={_SLOT: "w"})({"x": 0})

    assert _values(packaged) == _values(direct)


def test_a_copied_package_does_not_follow_an_edit_of_its_source(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    (source / "graphs" / "half.steps.yaml").write_text(_HALF.replace("value: 1", "value: 5"))

    assert _values(ModelPackage(path=str(out))({}))["a"] == 1


def test_a_referencing_package_follows_an_edit_of_its_source(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg", graphs="reference", weight_files="reference")
    (source / "graphs" / "half.steps.yaml").write_text(_HALF.replace("value: 1", "value: 5"))

    assert sorted(p.name for p in out.iterdir()) == [PACKAGE_FILE]
    info = read_package(out)
    assert info["graph"] == "../project/cfg/model.yaml"
    assert info["weights"][_SLOT]["path"] == "../project/runs/best.pth"
    assert _values(ModelPackage(path=str(out))({})) == {
        "a": 5,
        "weights": str(source / "runs" / "best.pth"),
        "b": "x",
    }


def test_graphs_and_weights_are_copied_or_referenced_independently(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg", graphs="reference", weight_files="copy")

    assert sorted(p.name for p in out.iterdir()) == [PACKAGE_FILE, "weights"]
    assert _values(ModelPackage(path=str(out))({}))["weights"] == str(out / "weights" / "best.pth")


def test_overrides_are_applied_last(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")

    record = ModelPackage(path=str(out), overrides={"flow.post.op.value": "y", _SLOT: "other.pth"})({})

    assert _values(record) == {"a": 1, "weights": "other.pth", "b": "y"}


def test_an_override_naming_an_included_block_reaches_it(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")

    assert _values(ModelPackage(path=str(out), overrides={"pre.scale.op.value": 3})({}))["a"] == 3


def test_a_changed_override_takes_effect_on_the_next_record(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    op = ModelPackage(path=str(out))
    assert _values(op({}))["b"] == "x"

    op.overrides = {"flow.post.op.value": "z"}

    assert _values(op({}))["b"] == "z"


def test_the_path_may_name_an_environment_variable(
    source: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _package(source, tmp_path / "pkg")
    monkeypatch.setenv("PACKAGES", str(tmp_path))

    assert _values(ModelPackage(path="$PACKAGES/pkg")({}))["b"] == "x"


def test_a_graph_whose_outputs_is_a_list_of_one_runs(source: Path, tmp_path: Path) -> None:
    (source / "cfg" / "model.yaml").write_text(_GRAPH.replace("outputs: post", "outputs: [post]"))
    out = _package(source, tmp_path / "pkg")

    assert _values(ModelPackage(path=str(out))({}))["b"] == "x"


def test_a_package_is_one_op_in_a_flow_graph(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    graph = f"""\
flow:
  model:
    op: !class:matrainer.model_package.ModelPackage
      path: {out}
      overrides: {{flow.post.op.value: y}}
  after:
    op: !class:recordstream.ops.structure.PutField {{key: c, value: 2}}
    from: model
outputs: after
"""
    document = confluid.load(graph)

    record = Subgraph(steps=document["flow"], result=document["outputs"])({})

    assert _values(record) == {"a": 1, "weights": str(out / "weights" / "best.pth"), "b": "y", "c": 2}


def test_an_op_that_has_run_pickles_without_its_loaded_graph(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    op = ModelPackage(path=str(out))
    expected = _values(op({}))

    clone = pickle.loads(pickle.dumps(op))

    assert clone._inner is None
    assert _values(clone({})) == expected


def test_constructing_the_op_reads_nothing(tmp_path: Path) -> None:
    op = ModelPackage(path=str(tmp_path / "nowhere"))

    assert op._inner is None


@pytest.mark.parametrize("path", ["", "nowhere"])
def test_a_missing_package_is_refused_naming_it(path: str, tmp_path: Path) -> None:
    where = str(tmp_path / path) if path else ""
    with pytest.raises(ValueError, match="ModelPackage: " + ("'path' is blank" if not path else "no package at")):
        ModelPackage(path=where)({})


def test_a_folder_without_a_package_file_is_refused_naming_the_file(tmp_path: Path) -> None:
    (tmp_path / "pkg").mkdir()

    with pytest.raises(ValueError, match=f"no package at {tmp_path / 'pkg'}: {PACKAGE_FILE} is missing"):
        ModelPackage(path=str(tmp_path / "pkg"))({})


def test_a_package_of_another_format_is_refused(source: Path, tmp_path: Path) -> None:
    out = _package(source, tmp_path / "pkg")
    text = (out / PACKAGE_FILE).read_text().replace(f"format: {PACKAGE_FORMAT}", "format: 99")
    (out / PACKAGE_FILE).write_text(text)

    with pytest.raises(ValueError, match="format 99, this matrainer reads format 1"):
        ModelPackage(path=str(out))({})



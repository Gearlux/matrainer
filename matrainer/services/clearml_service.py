"""The ClearML server as a workspace service — upstream's docker-compose stack, its state in the service's folder.

ClearML's server is seven containers (apiserver, webserver, fileserver, elasticsearch, mongo, redis,
agent-services), and upstream publishes the compose file that wires them. This service does NOT reimplement that
topology: it fetches upstream's file at a PINNED release tag, checks it against a pinned SHA-256, and layers a small
generated override on top.

**The override exists for one reason.** Upstream hardcodes ``/opt/clearml/...`` as the host side of every bind mount,
which would put the service's state outside the workspace and need root to create. Compose merges a service's
``volumes`` by container TARGET (an override naming the same target replaces the entry), so remapping every host
path into the service's data folder is exactly what an override is for. It is GENERATED from the upstream file, so
bumping :data:`CLEARML_SERVER_VERSION` cannot leave a path behind.

Docker runs these containers, not the service manager's supervisor (``supervised = False``): ``docker compose up -d``
/ ``down`` own them, so the class has its own start, stop, status, info and reset.
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
import os
import secrets
import shutil
import subprocess
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

from matrainer.services._messages import not_installed

#: Pinned upstream release. Bump this AND the digest below in the same edit.
CLEARML_SERVER_VERSION = "v2.4.0"

#: SHA-256 of upstream's ``docker/docker-compose.yml`` at that tag (verified 2026-08-01). A mismatch stops the start
#: rather than running an unexpected topology — refresh it with:  curl -sL <COMPOSE_URL> | shasum -a 256
COMPOSE_SHA256 = "c5905340c3edadc3c9b5e065e68437d64e6e697509bc7261973a448b74e74273"

COMPOSE_URL = "https://raw.githubusercontent.com/clearml/clearml-server/{version}/docker/docker-compose.yml"

#: The host-path prefix upstream hardcodes, and which the override rewrites.
UPSTREAM_HOST_ROOT = "/opt/clearml"

DEFAULT_WEB_PORT = 8080
DEFAULT_API_PORT = 8008
DEFAULT_FILES_PORT = 8081

#: Workspace ``.env`` keys holding the server login. The override references them as ``${...}`` and compose expands
#: them from the environment — never written into the file.
USER_ENV_KEY = "CLEARML_USERNAME"
PASSWORD_ENV_KEY = "CLEARML_PASSWORD"

#: Workspace ``.env`` keys holding the SDK credentials this service mints.
ACCESS_KEY_ENV = "CLEARML_API_ACCESS_KEY"
SECRET_KEY_ENV = "CLEARML_API_SECRET_KEY"

#: Seconds to wait for the apiserver before giving up on minting credentials.
API_READY_TIMEOUT = 180.0

_OVERRIDE_HEADER = """\
# =========================================================================
# AUTO-GENERATED FILE — DO NOT EDIT BY HAND
# Generated by: aisland clearml start
# Source module: matrainer/matrainer/services/clearml_service.py (write_override)
# To regenerate:  aisland clearml reset && aisland clearml start
# =========================================================================
# Layered over upstream's pinned docker-compose.yml. Its ONLY job is to move every
# host bind mount out of /opt/clearml and into this service's data folder,
# because service state must not live outside the workspace. Compose merges a
# service's `volumes` by container target, so each entry here REPLACES upstream's.
"""


class Files:
    """Where the service keeps its files, all inside its data folder."""

    def __init__(self, data_dir: Path) -> None:
        self.data_dir = data_dir
        self.upstream = data_dir / f"docker-compose-{CLEARML_SERVER_VERSION}.yml"
        self.override = data_dir / "aisland-override.yml"
        self.state = data_dir / "state"


def _installed() -> bool:
    """Whether the ClearML SDK can be imported, without importing it."""
    return importlib.util.find_spec("clearml") is not None


# --- the compose files ----------------------------------------------------------------------------------------------


# The context is the service manager's; matrainer names no type of it, so that it never depends on the manager.
def fetch_upstream(ctx: Any, files: Files) -> Path:
    """Upstream's compose at the pinned tag, checked BEFORE it is cached: a file that fails the digest is never
    written where a later start would take it as checked."""
    if files.upstream.exists():
        return files.upstream
    url = COMPOSE_URL.format(version=CLEARML_SERVER_VERSION)
    ctx.echo(f"Fetching clearml-server {CLEARML_SERVER_VERSION} compose...")
    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            payload: bytes = response.read()
    except (urllib.error.URLError, OSError) as exc:
        ctx.fail(f"Could not download {url}: {exc}")
    digest = hashlib.sha256(payload).hexdigest()
    if digest != COMPOSE_SHA256:
        ctx.fail(
            f"Checksum mismatch for clearml-server {CLEARML_SERVER_VERSION}.\n"
            f"  expected {COMPOSE_SHA256}\n  got      {digest}\n"
            "  Upstream changed the file at this tag, or the download was tampered with.\n"
            "  Verify it yourself before updating COMPOSE_SHA256 in matrainer/services/clearml_service.py."
        )
    files.data_dir.mkdir(parents=True, exist_ok=True)
    files.upstream.write_bytes(payload)
    return files.upstream


def write_override(files: Files) -> Path:
    """The override moving every host bind mount into the service's state folder, derived FROM upstream's file — a
    mount upstream adds is remapped, one it drops simply stops appearing."""
    document = yaml.safe_load(files.upstream.read_text()) or {}
    services: Dict[str, Any] = {}
    for name, spec in (document.get("services") or {}).items():
        remapped = [
            f"{_relocate(files, entry.split(':', 1)[0])}:{entry.split(':', 1)[1]}"
            for entry in (spec.get("volumes") or [])
            if isinstance(entry, str) and entry.startswith(UPSTREAM_HOST_ROOT + "/")
        ]
        if remapped:
            services[name] = {"volumes": remapped}
    files.override.write_text(
        _OVERRIDE_HEADER + yaml.safe_dump({"services": services}, sort_keys=True, default_flow_style=False)
    )
    return files.override


def _relocate(files: Files, host_path: str) -> str:
    """``/opt/clearml/data/redis`` → ``<data folder>/state/data/redis``, made now so Docker does not make it root's."""
    target = files.state / host_path[len(UPSTREAM_HOST_ROOT) :].lstrip("/")
    target.mkdir(parents=True, exist_ok=True)
    return str(target)


def compose(files: Files, *args: str) -> List[str]:
    """``docker compose`` over upstream's file, then the override (a later file applies over an earlier one)."""
    return ["docker", "compose", "-f", str(files.upstream), "-f", str(files.override), *args]


# --- the workspace .env and the login -------------------------------------------------------------------------------


def publish_hosts(ctx: Any, web_port: int) -> None:
    """The three hosts a ``ClearMLTracker`` reads, in the workspace ``.env``."""
    ctx.write_env(
        {
            "CLEARML_WEB_HOST": f"http://localhost:{web_port}",
            "CLEARML_API_HOST": f"http://localhost:{DEFAULT_API_PORT}",
            "CLEARML_FILES_HOST": f"http://localhost:{DEFAULT_FILES_PORT}",
        }
    )


def login(ctx: Any) -> Dict[str, str]:
    """The server login: the ``.env``'s when it has one, else the workspace's name and a generated password, written
    back so the login stays the one the server already has."""
    env = ctx.read_env()
    made = {
        USER_ENV_KEY: env.get(USER_ENV_KEY) or ctx.workspace_name,
        PASSWORD_ENV_KEY: env.get(PASSWORD_ENV_KEY) or secrets.token_urlsafe(18),
    }
    ctx.write_env(made)
    return made


def write_apiserver_conf(files: Files, credentials: Dict[str, str]) -> Path:
    """The fixed user, in the server's own config file, so login works headlessly.

    NOT through ``CLEARML__apiserver__auth__fixed_users__users__0__…`` environment variables: they cannot express a
    LIST OF OBJECTS, and the server dies on every login with ``FixedUser() argument after ** must be a mapping, not
    str`` (measured against v2.4.0). The password is a literal because the server must read it, so the file is 0600.
    """
    config_dir = files.state / "config"
    config_dir.mkdir(parents=True, exist_ok=True)
    target = config_dir / "apiserver.conf"
    target.write_text(
        "# AUTO-GENERATED by `aisland clearml start` — see matrainer/services/clearml_service.py\n"
        "auth {\n"
        "    fixed_users {\n"
        "        enabled: true\n"
        "        pass_hashed: false\n"
        "        users: [\n"
        f'            {{username: "{credentials[USER_ENV_KEY]}", '
        f'password: "{credentials[PASSWORD_ENV_KEY]}", '
        f'name: "{credentials[USER_ENV_KEY]}"}}\n'
        "        ]\n"
        "    }\n"
        "}\n"
    )
    target.chmod(0o600)
    return target


def _wait_for_api(timeout: float = API_READY_TIMEOUT) -> bool:
    """Poll ``debug.ping`` until the apiserver answers. Elasticsearch takes a while."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            request = urllib.request.Request(
                f"http://localhost:{DEFAULT_API_PORT}/debug.ping",
                data=b"{}",
                headers={"Content-Type": "application/json"},
            )
            with urllib.request.urlopen(request, timeout=5) as response:
                if response.status == 200:
                    return True
        except Exception:  # not up yet: any refusal or reset means ask again
            time.sleep(3)
    return False


def mint_credentials(ctx: Any, credentials: Dict[str, str]) -> Optional[Dict[str, str]]:
    """Log in as the fixed user and create SDK credentials, recording them in ``.env``. ``None`` (said, never raised)
    when the server is not ready or refuses: a convenience must not fail a stack that is otherwise up."""
    basic = base64.b64encode(f"{credentials[USER_ENV_KEY]}:{credentials[PASSWORD_ENV_KEY]}".encode()).decode()

    def call(endpoint: str, auth: str) -> Optional[Dict[str, Any]]:
        request = urllib.request.Request(
            f"http://localhost:{DEFAULT_API_PORT}/{endpoint}",
            data=b"{}",
            headers={"Content-Type": "application/json", "Authorization": auth},
        )
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                payload: Dict[str, Any] = json.loads(response.read())
                return payload
        except Exception as exc:  # the server's refusal of any kind is reported and skipped
            ctx.echo(f"  - {endpoint} failed: {exc}")
            return None

    session = call("auth.login", f"Basic {basic}")
    token = (session or {}).get("data", {}).get("token")
    if not token:
        ctx.echo("  - Could not log in; skipping credential creation.")
        return None
    created = call("auth.create_credentials", f"Bearer {token}")
    minted = (created or {}).get("data", {}).get("credentials") or {}
    access, secret = minted.get("access_key"), minted.get("secret_key")
    if not (access and secret):
        ctx.echo("  - Server returned no credentials; skipping.")
        return None
    ctx.write_env({ACCESS_KEY_ENV: access, SECRET_KEY_ENV: secret})
    return {ACCESS_KEY_ENV: access, SECRET_KEY_ENV: secret}


# --- the service ----------------------------------------------------------------------------------------------------


class ClearML:
    """The ClearML server: upstream's compose stack, run by Docker, its state in the service's data folder."""

    kind = "service"
    supervised = False

    def _check(self, ctx: Any) -> None:
        """The backend selected and Docker reachable — installing neither."""
        if not _installed():
            ctx.fail(not_installed(ctx, "ClearML", "clearml"))
        if shutil.which("docker") is None:
            ctx.fail(
                "The `docker` CLI was not found.\n"
                "  It is one of the workspace's system tools; install and link it with:\n"
                "      brew install docker docker-compose && brew link --overwrite docker"
            )
        if subprocess.run(["docker", "info"], capture_output=True, text=True).returncode != 0:
            ctx.fail("The Docker daemon is not reachable.\n  Start it with:\n      aisland docker start")

    def start(self, ctx: Any) -> None:
        """Bring the stack up (always detached — seven containers are not a foreground job)."""
        self._check(ctx)
        files = Files(ctx.data_dir)
        port = ctx.port or DEFAULT_WEB_PORT
        fetch_upstream(ctx, files)
        write_override(files)
        publish_hosts(ctx, port)
        credentials = login(ctx)
        # Written BEFORE `up`: the apiserver reads its config folder at startup.
        write_apiserver_conf(files, credentials)
        ctx.echo(f"ClearML: http://localhost:{port}")
        ctx.echo(f"  State: {files.state}")
        try:
            subprocess.check_call(compose(files, "up", "-d"), env={**os.environ, **credentials})
        except subprocess.CalledProcessError as exc:
            ctx.fail(f"`docker compose up` failed: {exc}")
        ctx.echo("  Waiting for the API (Elasticsearch takes ~30s)...")
        if not _wait_for_api():
            ctx.echo("  - API not ready yet; run `aisland clearml start` again to mint credentials.")
            return
        if mint_credentials(ctx, credentials):
            ctx.echo(f"  Credentials written to .env ({ACCESS_KEY_ENV} / {SECRET_KEY_ENV}).")
        ctx.echo(f"ClearML started. Log in at http://localhost:{port} as {credentials[USER_ENV_KEY]}.")

    def stop(self, ctx: Any) -> None:
        files = Files(ctx.data_dir)
        if not files.override.exists():
            ctx.echo("ClearML has never been started here; nothing to stop.")
            return
        subprocess.run(compose(files, "down"), check=False)
        ctx.echo("ClearML stopped.")

    def status(self, ctx: Any) -> None:
        files = Files(ctx.data_dir)
        if not files.override.exists():
            ctx.echo("  ClearML         : Not configured (run `aisland clearml start`)")
            return
        subprocess.run(compose(files, "ps"), check=False)

    def info(self, ctx: Any) -> None:
        files = Files(ctx.data_dir)
        ctx.echo(f"  Service       : {ctx.name}")
        ctx.echo(f"  Data dir      : {files.data_dir}")
        ctx.echo("  Lifecycle     : docker compose (NOT the process-compose supervisor)")
        ctx.echo(f"  Upstream      : clearml-server {CLEARML_SERVER_VERSION} (sha256 pinned)")
        ctx.echo(f"  Compose       : {files.upstream}")
        ctx.echo(f"  Override      : {files.override}")
        ctx.echo(f"  State         : {files.state}")
        ctx.echo(f"  Web / API     : http://localhost:{DEFAULT_WEB_PORT} / :{DEFAULT_API_PORT}")

    def reset(self, ctx: Any) -> None:
        """Tear the stack down and delete its state, its compose files and its volumes."""
        files = Files(ctx.data_dir)
        if files.override.exists():
            subprocess.run(compose(files, "down", "-v"), check=False)
        for path in (files.upstream, files.override):
            path.unlink(missing_ok=True)
        if files.state.exists():
            shutil.rmtree(files.state)
        ctx.echo("ClearML state removed.")
